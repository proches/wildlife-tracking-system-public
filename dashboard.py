"""Tiny optional dashboard for hotel operations and demo purposes.

Run with: python dashboard.py
It reads the files generated by the tracker and exposes a simple JSON/HTML
view. Flask is optional and isolated from the real-time tracking loop.
"""

import json
import os

import config

try:
    from flask import Flask, jsonify, render_template_string
except ImportError:  # pragma: no cover
    Flask = None


def _last_jsonl(path, limit=60):
    if not os.path.exists(path):
        return []
    with open(path, "r", encoding="utf-8") as f:
        lines = f.readlines()[-limit:]
    out = []
    for line in lines:
        try:
            out.append(json.loads(line))
        except json.JSONDecodeError:
            pass
    return out


def create_app():
    if Flask is None:
        raise RuntimeError("Install Flask from requirements-dashboard.txt to use the dashboard")
    app = Flask(__name__)

    @app.get("/api/metrics")
    def metrics():
        return jsonify(_last_jsonl(config.METRICS_JSONL, 120))

    @app.get("/api/health")
    def health():
        if not os.path.exists(config.SYSTEM_HEALTH_JSON):
            return jsonify({"available": False})
        with open(config.SYSTEM_HEALTH_JSON, "r", encoding="utf-8") as f:
            return jsonify(json.load(f))

    @app.get("/")
    def home():
        return render_template_string("""
<!doctype html><html><head><meta charset='utf-8'><meta http-equiv='refresh' content='10'>
<title>Melia Wildlife AI</title><style>body{font-family:Arial,sans-serif;margin:2rem;background:#101614;color:#f1f5f2}
.card{background:#19221f;padding:1rem;border-radius:12px;margin-bottom:1rem}.grid{display:grid;grid-template-columns:repeat(auto-fit,minmax(180px,1fr));gap:1rem}
h1{margin-bottom:.25rem}.muted{opacity:.7}code{color:#bfe7c5}</style></head>
<body><h1>Melia Serengeti Wildlife AI</h1><p class='muted'>Operational snapshot — refreshes every 10 seconds.</p>
<div id='app'>Loading…</div><script>
async function load(){const m=await fetch('/api/metrics').then(r=>r.json());const h=await fetch('/api/health').then(r=>r.json());
const x=m[m.length-1]||{};document.getElementById('app').innerHTML=`<div class='grid'>
<div class='card'><b>Stream</b><h2>${h.stream_ok?'ONLINE':'OFFLINE'}</h2></div>
<div class='card'><b>Camera</b><h2>${h.camera_status_ok?'OK':'CHECK'}</h2></div>
<div class='card'><b>FPS</b><h2>${x.fps??0}</h2></div>
<div class='card'><b>Inference</b><h2>${x.inference_ms??0} ms</h2></div>
<div class='card'><b>Tracks</b><h2>${x.target_locks??0}</h2></div>
<div class='card'><b>Reacquisitions</b><h2>${x.reacquisitions??0}</h2></div></div>
<div class='card'><b>Latest species activity</b><pre>${JSON.stringify(x.top_species||[],null,2)}</pre></div>`}
load();</script></body></html>
""")
    return app


if __name__ == "__main__":
    app = create_app()
    app.run(host=config.DASHBOARD_HOST, port=config.DASHBOARD_PORT)
